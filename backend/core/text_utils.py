#!/usr/bin/env python3
"""
文本处理工具函数
"""

import re


def preprocess_text_for_chattts(text: str) -> str:
    """
    预处理文本以适应 ChatTTS 模型
    - 转换全角字符为半角
    - 移除用户手动添加的控制标签（避免与系统自动添加的冲突）
    - 移除或替换不支持的字符
    """
    # 第一步：移除用户手动添加的 ChatTTS 控制标签
    # 这些标签会通过 API 参数自动添加，手动添加会导致冲突和 CUDA 错误
    control_tags = [
        r'\[oral_\d+\]',  # [oral_0] 到 [oral_9]
        r'\[laugh_\d+\]',  # [laugh_0] 到 [laugh_2]
        r'\[break_\d+\]',  # [break_0] 到 [break_7]
        r'\[speed_\d+\]',  # [speed_0] 到 [speed_9]
        r'\[laugh\]',  # [laugh]
        r'\[uv_break\]',  # [uv_break]
        r'\[v_break\]',  # [v_break]
        r'\[break\]',  # [break]
    ]

    for tag_pattern in control_tags:
        text = re.sub(tag_pattern, '', text)

    # 全角到半角映射
    fullwidth_to_halfwidth = {
        '（': '(', '）': ')', '【': '[', '】': ']',
        '｛': '{', '｝': '}', '「': '"', '」': '"',
        '『': '"', '』': '"', '［': '[', '］': ']',
        '。': '.', '，': ',', '！': '!', '？': '?',
        '；': ';', '：': ':', '"': '"', '"': '"',
        ''': "'", ''': "'", '、': ',', '·': '.',
        '～': '~', '＠': '@', '＃': '#', '＄': '$',
        '％': '%', '＆': '&', '＊': '*', '＋': '+',
        '－': '-', '／': '/', '＜': '<', '＝': '=',
        '＞': '>', '？': '?', '＾': '^', '＿': '_',
        '｀': '`', '｜': '|', '～': '~',
        '０': '0', '１': '1', '２': '2', '３': '3', '４': '4',
        '５': '5', '６': '6', '７': '7', '８': '8', '９': '9',
        'Ａ': 'A', 'Ｂ': 'B', 'Ｃ': 'C', 'Ｄ': 'D', 'Ｅ': 'E',
        'Ｆ': 'F', 'Ｇ': 'G', 'Ｈ': 'H', 'Ｉ': 'I', 'Ｊ': 'J',
        'Ｋ': 'K', 'Ｌ': 'L', 'Ｍ': 'M', 'Ｎ': 'N', 'Ｏ': 'O',
        'Ｐ': 'P', 'Ｑ': 'Q', 'Ｒ': 'R', 'Ｓ': 'S', 'Ｔ': 'T',
        'Ｕ': 'U', 'Ｖ': 'V', 'Ｗ': 'W', 'Ｘ': 'X', 'Ｙ': 'Y',
        'Ｚ': 'Z',
        'ａ': 'a', 'ｂ': 'b', 'ｃ': 'c', 'ｄ': 'd', 'ｅ': 'e',
        'ｆ': 'f', 'ｇ': 'g', 'ｈ': 'h', 'ｉ': 'i', 'ｊ': 'j',
        'ｋ': 'k', 'ｌ': 'l', 'ｍ': 'm', 'ｎ': 'n', 'ｏ': 'o',
        'ｐ': 'p', 'ｑ': 'q', 'ｒ': 'r', 'ｓ': 's', 'ｔ': 't',
        'ｕ': 'u', 'ｖ': 'v', 'ｗ': 'w', 'ｘ': 'x', 'ｙ': 'y',
        'ｚ': 'z',
    }

    # 转换全角到半角
    for fw, hw in fullwidth_to_halfwidth.items():
        text = text.replace(fw, hw)

    # 移除其他可能不支持的字符（保留中英文、数字、常用标点）
    # 注意：不再保留方括号 []，因为控制标签已经被移除
    allowed_pattern = r'[^\u4e00-\u9fa5a-zA-Z0-9\s\(\)\{\}\<\>\,\.\!\?\;\:\'\"\-\_\~\@\#\$\%\&\*\+\=\|\/\\\n]'
    text = re.sub(allowed_pattern, '', text)

    # 清理多余空格
    text = re.sub(r'\s+', ' ', text).strip()

    return text
